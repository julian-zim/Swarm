"""Export a checkpoint to ai/model.json and ai/model.js (the same data, loadable from file:// without fetch).
Run: .venv/bin/python -m ai.export ai/runs/run1/best.pt
"""
import json
import sys
from pathlib import Path

import torch

from . import space as S
from .train import Net

OUT = Path(__file__).resolve().parent


def export(ckpt_path, out_dir=OUT, decimals=8):
    ck = torch.load(ckpt_path, map_location='cpu')
    net = Net()
    net.load_state_dict(ck['state_dict'])
    w = net.weights()
    model = {'obsSize': S.OBS_SIZE, 'nActions': S.N_ACTIONS, 'hidden': int(w['b1'].shape[0])}
    for k, v in w.items():
        model[k] = [round(float(x), decimals) for x in v.reshape(-1)]
    text = json.dumps(model, separators=(',', ':'))
    (out_dir / 'model.json').write_text(text)
    (out_dir / 'model.js').write_text('// Generated by ai/export.py from ai/model.json. Loads the trained CPU network.\nTrainedAI.load(' + text + ');\n')
    return model


if __name__ == '__main__':
    m = export(sys.argv[1])
    print('exported', {k: (len(v) if isinstance(v, list) else v) for k, v in m.items()})
